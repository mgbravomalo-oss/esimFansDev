export function resolveDestinationCoveredCountries(dest?: Destination | null): DestinationCountryCoverage[] {
  if (!dest) return [];
  if (Array.isArray(dest.coveredCountries) && dest.coveredCountries.length > 0) {
    return dest.coveredCountries;
  }
  const code = (dest.code || '').toUpperCase().trim();
  const name = (dest.name || '').toLowerCase();

  if (code.startsWith('EU') || code === 'EUR' || name.includes('europa') || name.includes('europe')) {
    return EUROPE_35_COUNTRIES;
  }
  if (code.startsWith('NA') || code === 'NAM' || name.includes('norteamérica') || name.includes('norteamerica') || name.includes('north america')) {
    return NORTH_AMERICA_COUNTRIES;
  }
  if (code.startsWith('LATAM') || code.startsWith('SA-') || name.includes('latina') || name.includes('latam') || name.includes('sudamérica')) {
    return LATAM_COUNTRIES;
  }
  if (code.startsWith('ASIA') || name.includes('asia')) {
    return ASIA_COUNTRIES;
  }
  if (code.startsWith('ME') || name.includes('oriente') || name.includes('medio')) {
    return MIDDLE_EAST_COUNTRIES;
  }
  if (code.startsWith('GL') || code.startsWith('WORLD') || name.includes('global') || name.includes('mundial')) {
    return GLOBAL_140_COUNTRIES;
  }
  return [];
}

